    private void updateTabla() {
        // Actualizar tabla de últimos pedidos con más información
        List<Map<String, Object>> pedidos = dashboardDAO.getUltimosPedidos();
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        
        // Configurar columnas de la tabla
        String[] columnNames = {"ID", "Cliente", "Tipo", "Estado", "Fecha"};
        model.setColumnIdentifiers(columnNames);
        model.setRowCount(0); // Limpiar tabla
        
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM HH:mm");
        
        for (Map<String, Object> pedido : pedidos) {
            Object[] row = new Object[5];
            row[0] = pedido.get("id");
            row[1] = pedido.get("cliente") != null ? pedido.get("cliente") : "Cliente General";
            row[2] = formatTipoPedido((String) pedido.get("tipo"));
            row[3] = formatEstadoPedido((String) pedido.get("estado"));
            row[4] = pedido.get("fecha") != null ? sdf.format(pedido.get("fecha")) : "";
            model.addRow(row);
        }
        
        // Personalizar la apariencia de la tabla
        jTable1.setRowHeight(25);
        jTable1.getTableHeader().setBackground(new Color(102, 102, 102));
        jTable1.getTableHeader().setForeground(Color.WHITE);
        
        // Agregar información adicional de productos con bajo stock en una segunda vista
        addStockAlerts();
    }
    
    private String formatTipoPedido(String tipo) {
        if (tipo == null) return "N/A";
        switch (tipo.toLowerCase()) {
            case "delivery": return "Delivery";
            case "para_llevar": 
            case "llevar": return "Para Llevar";
            default: return tipo;
        }
    }
    
    private String formatEstadoPedido(String estado) {
        if (estado == null) return "N/A";
        switch (estado.toLowerCase()) {
            case "pendiente": return "⏳ Pendiente";
            case "en_preparacion": return "👨‍🍳 En Preparación";
            case "en_camino": return "🚗 En Camino";
            case "entregado": return "✅ Entregado";
            case "cancelado": return "❌ Cancelado";
            default: return estado;
        }
    }
    
