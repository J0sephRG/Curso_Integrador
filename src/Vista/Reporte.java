    private void startAutoRefresh() {
        // Configurar timer para actualización automática cada 30 segundos
        if (refreshTimer != null) {
            refreshTimer.stop();
        }
        
        refreshTimer = new Timer(30000, e -> {
            try {
                System.out.println("🔄 Actualizando dashboard automáticamente...");
                updateIndicadores();
                updateCharts();
                updateTabla();
                updateUserInfo();
            } catch (Exception ex) {
                System.err.println("❌ Error en actualización automática: " + ex.getMessage());
            }
        });
        
        refreshTimer.start();
        System.out.println("⏰ Actualización automática iniciada (cada 30 segundos)");
    }
    
    // Método para detener el timer cuando se cierre el panel
    public void stopRefresh() {
        try {
            if (refreshTimer != null && refreshTimer.isRunning()) {
                refreshTimer.stop();
                System.out.println("Timer de actualización detenido");
            }
            if (dashboardDAO != null) {
                dashboardDAO.cerrarConexion();
                System.out.println("Conexión a base de datos cerrada");
            }
        } catch (Exception e) {
            System.err.println("Error al cerrar recursos: " + e.getMessage());
        }
    }
    
