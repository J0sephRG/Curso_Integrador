    private void initializeDashboardSafely() {
        try {
            System.out.println("Iniciando conexión a base de datos...");
            dashboardDAO = new DashboardDAO();
            
            System.out.println("Configurando layout del dashboard...");
            setupDashboardLayout();
            
            System.out.println("Forzando tamaños de paneles...");
            forceChartPanelSizes();
            
            // MODO DE PRUEBA: Activar para probar visibilidad de paneles
            boolean modoDebug = false; // Cambiar a false cuando funcione
            
            if (modoDebug) {
                System.out.println("🧪 MODO DEBUG ACTIVADO - Probando visibilidad...");
                testPanelVisibility();
                
                // Esperar 3 segundos y luego cargar gráficos reales
                Timer delayTimer = new Timer(3000, e -> {
                    System.out.println("🔄 Cargando gráficos reales...");
                    loadSampleDataIfEmpty();
                    initializeDashboard();
                    ((Timer)e.getSource()).stop();
                });
                delayTimer.setRepeats(false);
                delayTimer.start();
            } else {
                System.out.println("Cargando datos del dashboard...");
                loadSampleDataIfEmpty();
                initializeDashboard();
            }
            
            System.out.println("Iniciando actualización automática...");
            startAutoRefresh();
            
            System.out.println("✅ Dashboard inicializado correctamente");
            
        } catch (Exception e) {
            System.err.println("❌ Error inicializando dashboard: " + e.getMessage());
            handleDashboardError("inicialización", e);
            
            // Mostrar datos por defecto
            showDefaultData();
        }
    }
    
